export function getCountryCode(name: string): string {
  if (!name) return "FR"; // Fallback to France
  const normalized = name.toLowerCase().trim();
  
  if (normalized === "ch" || normalized === "suisse") return "CH";
  if (normalized === "fr" || normalized === "france") return "FR";
  if (normalized === "be" || normalized === "belgique") return "BE";
  if (normalized === "lu" || normalized === "luxembourg") return "LU";
  
  const country = COUNTRIES.find(
    c => c.labelFr.toLowerCase() === normalized || 
         c.labelEn.toLowerCase() === normalized || 
         c.code.toLowerCase() === normalized
  );
  
  return country ? country.code : "FR";
}
